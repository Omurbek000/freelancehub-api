"""
FreelanceHub API - Фриланс биржа (Backend)

=====================================================================
 Описание проекта
=====================================================================

REST API платформа для соединения фрилансеров и заказчиков.
Заказчики создают проекты, фрилансеры подают предложения.
После завершения проекта — обмен отзывами и рейтингами.

=====================================================================
 Технологии
=====================================================================

- Python 3.12
- Django 5.2
- Django REST Framework 3.16
- JWT-аутентификация (SimpleJWT)
- Социальная аутентификация (allauth: GitHub, Google)
- Автогенерация документации (Swagger/YAML)
- Мультиязычность (modeltranslation: ru/en/ky)
- Фильтрация и пагинация (django-filter)
- Rate Limiting (DRF Throttling)

=====================================================================
 Модели данных
=====================================================================

- UserProfile  — пользователь (Freelancer / Client / Admin)
- Skill        — навыки (Python, JavaScript, React...)
- Category     — категории проектов
- Project      — проект заказчика
- Offer        — предложение фрилансера
- Review       — отзыв/рейтинг
- SocialLink   — социальные ссылки пользователя

=====================================================================
 API Эндпоинты
=====================================================================

Аутентификация:
  POST   /register/          — регистрация нового пользователя
  POST   /login/             — логин (получение JWT-токенов)
  POST   /logout/            — выход (чёрный список refresh-токена)

Пользователи:
  GET    /user/              — список пользователей (авторизация)
  GET    /user/<id>/         — профиль пользователя (свой профиль)
  GET    /users-simple/      — CRUD пользователей (авторизация)

Проекты:
  GET    /projects/          — CRUD проектов (авторизация)
  GET    /project/           — список проектов (публичный)
  GET    /project/<id>/      — детали проекта (публичный)

Категории:
  GET    /categories/        — CRUD категорий (авторизация)

Предложения:
  GET    /offers/            — CRUD предложений (авторизация)
  GET    /offer/             — список предложений (публичный)
  GET    /offer/<id>/        — детали предложения (авторизация)

Отзывы:
  GET    /reviews/           — CRUD отзывов (авторизация)

Документация:
  GET    /docs/              — Swagger UI (автогенерация)

Админ-панель:
  GET    /admin/             — Django Admin

=====================================================================
 Роли пользователей
=====================================================================

- Client    — заказчик (создаёт проекты)
- Freelancer — испполнитель (подает предложения)
- Admin     — администратор платформы

=====================================================================
 Rate Limiting (ограничение запросов)
=====================================================================

- Анонимные:     100 запросов/час
- Авторизованные: 1000 запросов/час
- Логин:          5 попыток/минуту

=====================================================================
 JWT-токены
=====================================================================

- Access-токен:  30 минут
- Refresh-токен: 7 дней
- Формат:        Authorization: Bearer <access_token>

=====================================================================
 Быстрый старт
=====================================================================

1. Установить зависимости:
   pip install -r requirements.txt

2. Создать .env файл:
   SECRET_KEY=your-secret-key

3. Применить миграции:
   python manage.py migrate

4. Создать суперпользователя:
   python manage.py createsuperuser

5. Запустить сервер:
   python manage.py runserver

6. Открыть API:
   - Swagger: http://127.0.0.1:8000/docs/
   - Admin:   http://127.0.0.1:8000/admin/

=====================================================================
 Структура проекта
=====================================================================

freelancehub/
├── freelancehub/       — настройки проекта
│   ├── settings.py     — основные настройки
│   ├── urls.py         — корневые URL
│   └── wsgi.py         — WSGI-точка входа
├── freelance/          — основное приложение
│   ├── models.py       — модели базы данных
│   ├── serializers.py  — сериализаторы DRF
│   ├── views.py        — API-представления
│   ├── urls.py         — URL-маршруты API
│   ├── permissions.py  — классы разрешений
│   ├── filters.py      — фильтры запросов
│   ├── pagination.py   — пагинация
│   ├── translation.py  — переводы моделей
│   ├── admin.py        — настройка админки
│   └── migrations/     — миграции БД
├── manage.py           — управление Django
├── db.sqlite3          — база данных SQLite
├── requirements.txt    — зависимости
├── .env                — переменные окружения
└── README.py           — этот файл
"""
